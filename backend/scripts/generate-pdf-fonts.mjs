#!/usr/bin/env node
// Regenerates the embedded PDF export fonts from unmodified Liberation 2.x TTFs
// (SIL OFL 1.1, see src/documents/fonts/LICENSE-Liberation.txt). The files are
// inlined as base64 so both the tsc build and the SAM esbuild bundle ship them
// without asset-copy steps.
// Usage: node scripts/generate-pdf-fonts.mjs [/usr/share/fonts/truetype/liberation]
import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { join } from 'node:path';

const sourceDir = process.argv[2] || '/usr/share/fonts/truetype/liberation';
const outDir = new URL('../src/documents/fonts/', import.meta.url);
for (const [file, exportName] of [['LiberationSerif-Regular.ttf', 'liberationSerifRegular'], ['LiberationSerif-Bold.ttf', 'liberationSerifBold']]) {
  const bytes = readFileSync(join(sourceDir, file));
  const sha = createHash('sha256').update(bytes).digest('hex');
  writeFileSync(new URL(`${exportName}.ts`, outDir), `// Generated by scripts/generate-pdf-fonts.mjs from unmodified ${file} (SIL OFL 1.1). Do not edit.\n// sha256 ${sha}\nexport const ${exportName} = '${bytes.toString('base64')}';\n`);
  console.log(file, bytes.length, sha);
}
